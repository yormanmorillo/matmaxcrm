import { chromium } from 'playwright'
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const suffix = Date.now().toString().slice(-5)
await page.goto('https://crm.matmax.site/login', { waitUntil: 'networkidle' })
await page.fill('#login-user', process.env.ADMIN_USER); await page.fill('#login-password', process.env.ADMIN_PASS)
await page.getByRole('button', { name: /Iniciar sesión/i }).click()
await page.waitForURL(u => !u.pathname.startsWith('/login'))
await page.goto('https://crm.matmax.site/teams', { waitUntil: 'networkidle' })
await page.getByRole('button', { name: /Nuevo equipo/i }).click()
const d = page.getByRole('dialog'); await d.waitFor({ state: 'visible' })
await d.locator('input').first().fill(`Equipo E2E ${suffix}`)
await d.getByRole('button', { name: /Crear equipo/i }).click()
await d.waitFor({ state: 'hidden', timeout: 15000 })
await page.waitForTimeout(900)
const created = await page.getByText(`Equipo E2E ${suffix}`, { exact: true }).count()
console.log('equipo creado:', created)
await page.getByText(`Equipo E2E ${suffix}`, { exact: true }).first().click()
await page.waitForTimeout(600)
await page.getByRole('button', { name: /^Eliminar$/ }).click()
await page.waitForTimeout(300)
await page.getByRole('button', { name: /Eliminar equipo/i }).click()
await page.waitForTimeout(900)
const remaining = await page.getByText(`Equipo E2E ${suffix}`, { exact: true }).count()
console.log('equipo eliminado:', remaining === 0)
await browser.close()
